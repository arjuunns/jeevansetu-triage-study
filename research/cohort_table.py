"""Table 1 (cohort characteristics) for the paper, from data/mimic_ed_cohort.json.

    python3 -I research/cohort_table.py     # writes paper/tables/cohort.tex

Medians and quartiles use statistics.quantiles(method="inclusive").
Percentages are of all 207 stays; vital-sign rows report the number recorded.
"""

import json
import statistics
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COHORT = ROOT / "data" / "mimic_ed_cohort.json"
OUT = ROOT / "paper" / "tables" / "cohort.tex"

VITALS = [
    ("heartRate", "Heart rate (/min)"),
    ("respiratoryRate", "Respiratory rate (/min)"),
    ("oxygenSaturation", "SpO$_2$ (\\%)"),
    ("systolicBp", "Systolic BP (mmHg)"),
    ("temperatureC", "Temperature ($^\\circ$C)"),
]
ARRIVAL = [("AMBULANCE", "Ambulance"), ("WALK IN", "Walk in"), ("UNKNOWN", "Unknown"), ("OTHER", "Other")]
DISPOSITION = [
    ("ADMITTED", "Admitted"),
    ("HOME", "Home"),
    ("TRANSFER", "Transfer"),
    ("LEFT WITHOUT BEING SEEN", "Left without being seen"),
    ("LEFT AGAINST MEDICAL ADVICE", "Left against medical advice"),
    ("ELOPED", "Eloped"),
]


def median_iqr(values):
    q1, med, q3 = statistics.quantiles(values, n=4, method="inclusive")
    return f"{fmt(med)} ({fmt(q1)}--{fmt(q3)})"


def fmt(x):
    return f"{x:.0f}" if float(x).is_integer() else f"{x:.1f}"


def count_row(label, k, n):
    return f"\\quad {label} & {k} ({100 * k / n:.1f}) \\\\"


def main():
    cases = json.loads(COHORT.read_text())["cases"]
    n = len(cases)
    inputs = [c["input"] for c in cases]
    rows = [f"Stays & {n} \\\\"]

    rows.append(f"Age, years, median (IQR) & {median_iqr([i['age'] for i in inputs])} \\\\")
    rows.append(count_row("Female, n (\\%)", sum(i["gender"] == "FEMALE" for i in inputs), n).replace("\\quad ", ""))

    rows.append("Arrival, n (\\%) & \\\\")
    arrival = Counter(i.get("arrivalTransport") for i in inputs)
    rows += [count_row(label, arrival[key], n) for key, label in ARRIVAL]

    rows.append("Vital signs, median (IQR) [n] & \\\\")
    for key, label in VITALS:
        values = [i["vitals"][key] for i in inputs if isinstance(i["vitals"].get(key), (int, float))]
        rows.append(f"\\quad {label} & {median_iqr(values)} [{len(values)}] \\\\")
    pain = [i["painScore"] for i in inputs if isinstance(i.get("painScore"), int)]
    rows.append(f"\\quad Pain score (0--10) & {median_iqr(pain)} [{len(pain)}] \\\\")

    rows.append("Reference ESI (triage nurse), n (\\%) & \\\\")
    esi = Counter(c["label"]["esi"] for c in cases)
    rows += [count_row(f"ESI {level}", esi[level], n) for level in range(1, 6)]

    rows.append("ED disposition, n (\\%) & \\\\")
    disposition = Counter(c["outcome"]["disposition"] for c in cases)
    rows += [count_row(label, disposition[key], n) for key, label in DISPOSITION]
    if sum(disposition[key] for key, _ in DISPOSITION) != n:
        raise SystemExit(f"unlisted dispositions: {disposition}")

    body = "\n".join(rows)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        "% Generated by research/cohort_table.py from data/mimic_ed_cohort.json. Do not edit by hand.\n"
        "\\begin{table}[t]\n\\centering\n\\caption{Cohort characteristics (MIMIC-IV-ED demo, 207 ED stays). [n]: stays with the value recorded.}\n"
        "\\label{tab:cohort}\n\\footnotesize\n\\begin{tabular}{@{}lr@{}}\n\\toprule\n"
        "Characteristic & Value \\\\\n\\midrule\n"
        f"{body}\n\\bottomrule\n\\end{{tabular}}\n\\end{{table}}\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
