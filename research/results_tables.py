"""Results tables and the component-effect figure for the paper, from
research/results/summary.json. Runs that are missing or still running are shown
as pending, so this can be re-run as more runs finish.

    python3 -I research/analyze.py          # refresh summary.json first
    python3 -I research/results_tables.py   # writes paper/tables/{main_results,high_acuity,comparisons,prior_studies}.tex
                                            # and paper/figures/components.tex
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SUMMARY = ROOT / "research" / "results" / "summary.json"
TABLES = ROOT / "paper" / "tables"
FIGURES = ROOT / "paper" / "figures"
HEADER = "% Generated by research/results_tables.py from research/results/summary.json. Do not edit by hand.\n"

MODELS = [
    ("qwen2.5:7b", "Qwen2.5 7B"),
    ("llama3.1:8b", "Llama 3.1 8B"),
    ("gemma3:12b", "Gemma 3 12B"),
    ("medgemma:27b", "MedGemma 27B"),  # mid-sized medical model, run on the university GPU
]

# (label in the tables, label used by analyze.py, (useRag, useSafety, useGuide, safetyNotice))
SETUPS = [
    ("LLM only", "LLM only", (False, False, False, True)),
    ("+ safety", "LLM + safety", (False, True, False, True)),
    ("+ ESI guide", "LLM + ESI guide", (False, False, True, True)),
    ("+ ESI guide + safety", "LLM + ESI guide + safety", (False, True, True, True)),
    ("+ RAG", "LLM + RAG", (True, False, False, True)),
    ("Full (RAG + safety)", "Full (LLM + RAG + safety)", (True, True, False, True)),
    ("+ safety, no notice$^{a}$", "LLM + safety, no negative notice (exploratory)", (False, True, False, False)),
]
SHORT = {analyze: short for short, analyze, _ in SETUPS} | {"Rules only": "Rules only"}

# Component effects for the figure: (row label, setup A, setup B), B = A plus the component.
EFFECTS = [
    ("Safety", "LLM only", "LLM + safety"),
    ("ESI guide", "LLM only", "LLM + ESI guide"),
    ("RAG", "LLM only", "LLM + RAG"),
    ("Safety, with RAG", "LLM + RAG", "Full (LLM + RAG + safety)"),
    ("Safety, with guide", "LLM + ESI guide", "LLM + ESI guide + safety"),
    ("Safety, no notice$^{a}$", "LLM only", "LLM + safety, no negative notice (exploratory)"),
]
MARKS = {  # black-and-white markers, one per model
    "qwen2.5:7b": ("circle", "fill=black", "draw=black"),
    "llama3.1:8b": ("rectangle", "fill=white", "draw=black, thick"),
    "gemma3:12b": ("regular polygon, regular polygon sides=3", "fill=gray!50", "draw=black"),
    "medgemma:27b": ("diamond", "fill=white", "draw=black, thick"),
}

PENDING = "\\TODO{pending}"

# Earlier LLM triage studies for the comparison table: (study, model, data and model input, scale and reference, result).
# Wording and numbers as stated in paper/sections/02-related-work.tex; for Wong and Wong, the five levels, one centre and
# blinded senior nurses are from their abstract (Europe PMC, PMID 41587455, read 2 Nov 2026).
PRIOR = [
    (
        "Williams et al.~\\cite{williamsUseLargeLanguage2024}",
        "GPT-4",
        "10{,}000 pairs of adult ED visits with different ESI levels; first ED notes",
        "Recorded ESI level",
        "Chose the more urgent patient in 89\\% of pairs; 0.88 against a physician's 0.86 on 500 pairs",
    ),
    (
        "Masanneck et al.~\\cite{masanneckTriagePerformanceLarge2024}",
        "GPT-4-based ChatGPT and other LLMs",
        "124 written cases",
        "Manchester Triage System; answers agreed by trained staff",
        "QWK 0.67 (untrained doctors 0.68)",
    ),
    (
        "Gaber et al.~\\cite{gaberEvaluatingLargeLanguage2025}",
        "Claude 3.5 Sonnet, Claude 3 Sonnet, Claude 3 Haiku; RAG workflow over 30 million PubMed abstracts",
        "2{,}000 MIMIC-IV-ED cases; history of present illness from the discharge notes, with triage vital signs",
        "ESI by the triage nurse",
        "Exact 59.00--65.75\\% (Claude 3 Haiku to the RAG workflow)",
    ),
    (
        "Wong and Wong~\\cite{wongMultiEvidenceClinicalReasoning2026}",
        "DeepSeek-V3, with and without retrieval of guideline sections and similar past cases",
        "236 triage encounters at one hospital in Hong Kong",
        "Hong Kong triage guidelines (5 levels); consensus of blinded senior triage nurses",
        "QWK 0.801 without and 0.902 with retrieval; accuracy 0.542 and 0.802",
    ),
]


def flags(cfg):
    return (cfg["useRag"], cfg["useSafety"], cfg["useGuide"], cfg.get("safetyNotice", True))


def find(summary, model, key):
    for r in summary["runs"]:
        c = r["config"]
        if c.get("mode") == "llm" and c["model"] == model and flags(c) == key and r["complete"]:
            return r
    return None


def rules_only(summary):
    return next(r for r in summary["runs"] if r["run"] == "rules-only")


def pct(m, ci=True):
    v = f"{100 * m['value']:.1f}"
    return f"{v} {{\\scriptsize({100 * m['ci95'][0]:.1f}--{100 * m['ci95'][1]:.1f})}}" if ci else v


def signed(v, fmt):
    return f"$-${-v:{fmt}}" if v < 0 else f"{v:{fmt}}"


def kappa(m):
    lo, hi = m["ci95"]
    return f"{signed(m['value'], '.2f')} {{\\scriptsize({signed(lo, '.2f')} to {signed(hi, '.2f')})}}"


def pval(p):
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def main_row(r):
    m = r["metrics"]
    return [pct(m["exact"]), pct(m["withinOne"]), pct(m["underTriage"]), pct(m["overTriage"]), kappa(m["quadraticKappa"])]


def acuity_row(r):
    m = r["metrics"]
    ece = r["calibration"]["ece"] if r.get("calibration") else None
    return [
        pct(m["highAcuitySensitivity"]),
        pct(m["highAcuitySpecificity"]),
        pct(m["highAcuityPPV"], ci=False),
        pct(m["highAcuityNPV"], ci=False),
        pct(m["severeUnderTriage"], ci=False),
        f"{100 * r['admitted']['underTriage']:.1f}",
        str(r["admitted"]["missedHighAcuity"]),
        f"{ece:.2f}" if ece is not None else "--",
    ]


def body(summary, row_fn, ncols):
    rows = ["Rules only (no LLM) & " + " & ".join(row_fn(rules_only(summary))) + " \\\\", "\\midrule"]
    for i, (model, name) in enumerate(MODELS):
        rows.append(f"\\multicolumn{{{ncols + 1}}}{{@{{}}l}}{{\\emph{{{name}}}}} \\\\")
        runs = [find(summary, model, key) for _, _, key in SETUPS]
        if not any(runs):
            rows.append(f"\\quad All setups & \\multicolumn{{{ncols}}}{{c}}{{\\TODO{{runs in progress}}}} \\\\")
        else:
            for (label, _, _), r in zip(SETUPS, runs):
                cells = " & ".join(row_fn(r)) if r else f"\\multicolumn{{{ncols}}}{{c}}{{{PENDING}}}"
                rows.append(f"\\quad {label} & {cells} \\\\")
        if i < len(MODELS) - 1:
            rows.append("\\midrule")
    return "\n".join(rows)


def table(env, label, caption, colspec, head, rows, note):
    return (
        HEADER + f"\\begin{{{env}}}[t]\n\\centering\n\\caption{{{caption}}}\n\\label{{{label}}}\n\\footnotesize\n"
        "\\setlength{\\tabcolsep}{3.5pt}\n"
        f"\\begin{{tabular}}{{@{{}}{colspec}@{{}}}}\n\\toprule\n{head} \\\\\n\\midrule\n{rows}\n\\bottomrule\n"
        f"\\end{{tabular}}\n\n\\vspace{{2pt}}\n{{\\scriptsize {note}}}\n\\end{{{env}}}\n"
    )


NOTE_A = "$^{a}$Exploratory, added after the first Qwen2.5 results: rules and override as in + safety, but the prompt mentions safety only when a rule fires."


def comparison_ok(summary, c):
    if c["a"] == "Rules only":
        a_ok = True
    else:
        a_ok = find(summary, c["model"], next(k for _, l, k in SETUPS if l == c["a"])) is not None
    b_ok = find(summary, c["model"], next(k for _, l, k in SETUPS if l == c["b"])) is not None
    return a_ok and b_ok


def comparisons(summary):
    rows = []
    for i, (model, name) in enumerate(MODELS):
        rows.append(f"\\multicolumn{{7}}{{@{{}}l}}{{\\emph{{{name}}}}} \\\\")
        cs = [c for c in summary["comparisons"] if c["model"] == model]
        if not cs:
            rows.append("\\quad All comparisons & \\multicolumn{6}{c}{\\TODO{runs in progress}} \\\\")
        for c in cs:
            pair = f"\\quad {SHORT[c['a']]} vs {SHORT[c['b']]}"
            if not comparison_ok(summary, c):
                rows.append(f"{pair} & \\multicolumn{{6}}{{c}}{{{PENDING}}} \\\\")
                continue
            u, e = c["underTriage"], c["exact"]
            rows.append(
                f"{pair} & {100 * u['a']:.1f} & {100 * u['b']:.1f} & {pval(u['pHolm'])} & {100 * e['a']:.1f} & {100 * e['b']:.1f} & {pval(e['pHolm'])} \\\\"
            )
        if i < len(MODELS) - 1:
            rows.append("\\midrule")
    head = (
        "& \\multicolumn{3}{c}{Under-triage (\\%)} & \\multicolumn{3}{c}{Exact agreement (\\%)} \\\\\n"
        "\\cmidrule(lr){2-4}\\cmidrule(l){5-7}\nComparison (A vs B) & A & B & $p$ & A & B & $p$"
    )
    note = (
        "Exact McNemar test on the same 207 patients; $p$ values Holm-adjusted within each model and measure, "
        "with the exploratory comparisons as a separate family. " + NOTE_A
    )
    return table("table*", "tab:comparisons", "Paired comparisons between setups.", "lcccccc", head, "\n".join(rows), note)


def ours_result(summary, model, name):
    """LLM-only value and the best over the six main setups (exploratory one left out)."""
    runs = [find(summary, model, key) for _, _, key in SETUPS if key[3]]
    if not all(runs):
        return f"{name}: {PENDING}"
    exact = [r["metrics"]["exact"]["value"] for r in runs]
    qwk = [r["metrics"]["quadraticKappa"]["value"] for r in runs]
    return (
        f"{name}: exact {100 * exact[0]:.1f}\\% alone (best {100 * max(exact):.1f}\\%); "
        f"QWK {signed(qwk[0], '.2f')} (best {signed(max(qwk), '.2f')})"
    )


def prior_studies(summary):
    names = [n for _, n in MODELS]
    ours = (
        "This study",
        f"{', '.join(names[:-1])} and {names[-1]} (local, 4-bit), alone and with safety rules, ESI guide or guideline RAG",
        "207 MIMIC-IV-ED demo visits; triage record only (age, sex, arrival, main complaint, first vital signs, pain score)",
        "ESI by the triage nurse",
        " \\newline ".join(ours_result(summary, m, n) for m, n in MODELS),
    )
    rows = []
    for p in PRIOR:
        rows += [" & ".join(p) + " \\\\", "\\addlinespace"]
    rows[-1] = "\\midrule"
    rows.append(" & ".join(ours) + " \\\\")
    col = lambda w: f">{{\\raggedright\\arraybackslash}}p{{{w}\\linewidth}}"
    colspec = "".join(col(w) for w in (0.10, 0.19, 0.21, 0.14, 0.30))
    note = (
        "QWK: quadratic-weighted kappa. Exact or accuracy: share of patients given the same level as the reference. "
        "For this study, ``alone'' is the LLM-only setup and ``best'' the highest value over the six main setups in Table~\\ref{tab:main}."
    )
    return table(
        "table*", "tab:prior",
        "Results reported by earlier LLM triage studies and by this study. The studies differ in patients, triage scale, "
        "reference standard, model input and measure, so the numbers are not directly comparable.",
        colspec, "Study & Model & Data and model input & Scale and reference & Reported result", "\n".join(rows), note,
    )


def effect_values(summary, model, a, b):
    """Change in under-triage (paired, with Holm p) and in high-acuity sensitivity, in percentage points."""
    c = next((c for c in summary["comparisons"] if c["model"] == model and c["a"] == a and c["b"] == b), None)
    if c is None or not comparison_ok(summary, c):
        return None
    ra = find(summary, model, next(k for _, l, k in SETUPS if l == a))
    rb = find(summary, model, next(k for _, l, k in SETUPS if l == b))
    sens = 100 * (rb["metrics"]["highAcuitySensitivity"]["value"] - ra["metrics"]["highAcuitySensitivity"]["value"])
    u = c["underTriage"]
    return {"under": 100 * (u["b"] - u["a"]), "pHolm": u["pHolm"], "sens": sens}


def tick(t):
    return "0" if t == 0 else (f"+{t}" if t > 0 else f"$-${-t}")


def marker_size(shape):
    return "2.2mm" if shape == "diamond" else "2.0mm" if "polygon" in shape else "1.6mm"


def axis_range(values):
    """Axis limits and tick step: steps of 10, or 20 when the range is wide."""
    lo = min(min(values, default=0), 0)
    hi = max(max(values, default=0), 0)
    step = 10 if hi - lo <= 60 else 20
    return step * int(lo // step), step * int(-(-hi // step)), step


def panel(summary, key, title, y0, show_sig):
    """One dot-plot panel in TikZ; y0 is the top of the panel in cm."""
    width, left, row_h = 4.3, 0.0, 0.5
    vals = {}
    for model, _ in MODELS:
        for label, a, b in EFFECTS:
            v = effect_values(summary, model, a, b)
            if v:
                vals[(model, label)] = v
    lo, hi, step = axis_range([v[key] for v in vals.values()])
    x = lambda d: left + width * (d - lo) / (hi - lo)
    n = len(EFFECTS)
    bottom = y0 - row_h * n
    out = [f"\\node[font=\\scriptsize\\bfseries, anchor=south west, inner sep=0] at (-3.0, {y0 + 0.15:.2f}) {{{title}}};"]
    for t in range(lo, hi + 1, step):
        out.append(f"\\draw[gray!35] ({x(t):.3f}, {bottom:.2f}) -- ({x(t):.3f}, {y0:.2f});")
        out.append(f"\\draw ({x(t):.3f}, {bottom:.2f}) -- ++(0, -0.07) node[below, font=\\tiny, inner sep=1.5pt] {{{tick(t)}}};")
    out.append(f"\\draw[dashed] ({x(0):.3f}, {bottom:.2f}) -- ({x(0):.3f}, {y0:.2f});")
    out.append(f"\\draw ({x(lo):.3f}, {bottom:.2f}) -- ({x(hi):.3f}, {bottom:.2f});")
    for i, (label, _, _) in enumerate(EFFECTS):
        yc = y0 - row_h * (i + 0.5)
        out.append(f"\\node[font=\\scriptsize, anchor=east, inner sep=1pt] at ({left - 0.1:.2f}, {yc:.2f}) {{{label}}};")
        for j, (model, _) in enumerate(MODELS):
            v = vals.get((model, label))
            if not v:
                continue
            yy = yc + 0.1 * ((len(MODELS) - 1) / 2 - j)
            shape, fill, draw = MARKS[model]
            size = marker_size(shape)
            out.append(f"\\node[{shape}, {fill}, {draw}, inner sep=0, minimum size={size}] at ({x(v[key]):.3f}, {yy:.3f}) {{}};")
            if show_sig and v["pHolm"] < 0.05:
                out.append(f"\\node[font=\\tiny, anchor=west, inner sep=1pt] at ({x(v[key]) + 0.08:.3f}, {yy + 0.02:.3f}) {{*}};")
    return out, bottom


def components(summary):
    top1 = 0.0
    p1, b1 = panel(summary, "under", "(a) Under-triage, change in points (lower is safer)", top1, True)
    top2 = b1 - 1.05
    p2, b2 = panel(summary, "sens", "(b) High-priority sensitivity, change in points (higher is better)", top2, False)
    have = {m for m, _ in MODELS if any(effect_values(summary, m, a, b) for _, a, b in EFFECTS)}
    legend = []
    for k, (model, name) in enumerate(MODELS):  # two columns
        lx, ly = -3.0 + 4.0 * (k % 2), b2 - 0.75 - 0.4 * (k // 2)
        shape, fill, draw = MARKS[model]
        text = name if model in have else f"{name} (pending)"
        legend.append(f"\\node[{shape}, {fill}, {draw}, inner sep=0, minimum size={marker_size(shape)}] at ({lx:.2f}, {ly:.2f}) {{}};")
        legend.append(f"\\node[font=\\scriptsize, anchor=west, inner sep=1.5pt] at ({lx + 0.1:.2f}, {ly:.2f}) {{{text}}};")
    lines = p1 + p2 + legend
    return (
        HEADER
        + "\\begin{figure}[t]\n\\centering\n\\begin{tikzpicture}\n"
        + "\n".join(lines)
        + "\n\\end{tikzpicture}\n"
        "\\caption{Change when each component is added, for each model (B minus A, same 207 patients). "
        "``With RAG'' and ``with guide'' add the safety rules to a setup that already has that component. "
        "*Holm-adjusted McNemar $p<0.05$ for under-triage. $^{a}$Exploratory.}\n"
        "\\label{fig:components}\n\\end{figure}\n"
    )


def validity_note(summary):
    done = [r for r in summary["runs"] if r["complete"] and r["config"].get("mode") == "llm"]
    bad = sum(r["fallback"] + r["error"] for r in done)
    if bad == 0:
        return f"All {len(done)} finished LLM runs had valid model output for all 207 patients (no fallback or error cases)."
    return f"Fallback or error cases across the {len(done)} finished LLM runs: {bad}."


def admitted_n(summary):
    return rules_only(summary)["admitted"]["n"]


def main():
    summary = json.loads(SUMMARY.read_text())
    TABLES.mkdir(exist_ok=True)
    main_head = "Setup & Exact & Within one & Under-triage & Over-triage & QWK"
    (TABLES / "main_results.tex").write_text(
        table(
            "table*", "tab:main", "Agreement with the triage nurse's ESI level (\\%, with 95\\% bootstrap CI). QWK: quadratic-weighted kappa.",
            "lccccc", main_head, body(summary, main_row, 5),
            validity_note(summary) + " " + NOTE_A,
        )
    )
    acuity_head = (
        "Setup & Sensitivity & Specificity & PPV & NPV & Severe UT & UT, admitted & Missed & ECE"
    )
    (TABLES / "high_acuity.tex").write_text(
        table(
            "table*", "tab:acuity",
            "Finding high-priority patients (ESI 1 or 2 against 3 to 5, \\%, with 95\\% CI for sensitivity and specificity).",
            "lcccccccc", acuity_head, body(summary, acuity_row, 8),
            f"Severe UT: under-triage by two or more levels. UT, admitted: under-triage among the {admitted_n(summary)} patients later admitted. "
            "Missed: admitted ESI 1 or 2 patients rated ESI 3 or lower. ECE: expected calibration error of the model's stated confidence. " + NOTE_A,
        )
    )
    (TABLES / "comparisons.tex").write_text(comparisons(summary))
    (TABLES / "prior_studies.tex").write_text(prior_studies(summary))
    (FIGURES / "components.tex").write_text(components(summary))
    print("wrote paper/tables/main_results.tex, high_acuity.tex, comparisons.tex, prior_studies.tex and paper/figures/components.tex")


if __name__ == "__main__":
    main()
