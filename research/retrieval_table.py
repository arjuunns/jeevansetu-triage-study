"""Retrieval-quality table for the paper, from research/retrieval_eval/results.json
and the two retrieval caches (share of passages per source document).

    python3 -I research/retrieval_table.py     # writes paper/tables/retrieval.tex
"""

import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "research" / "retrieval_eval" / "results.json"
CACHES = {"baseline": ROOT / "research" / "retrieval_cache_baseline.json", "improved": ROOT / "research" / "retrieval_cache.json"}
OUT = ROOT / "paper" / "tables" / "retrieval.tex"

METRICS = [
    ("p5", "Precision at 5 (score $\\geq$ 1)"),
    ("strictP5", "Strict precision at 5 (score 2)"),
    ("meanRel", "Mean score (0--2)"),
    ("ndcg5", "nDCG at 5"),
]
SOURCES = [("ESI handbook (5th ed.)", "Emergency_Severity"), ("ESI guide (ours)", "ESI algorithm summary"), ("WHO and ICRC manual", "9789241513081")]


def cell(m):
    return f"{m['mean']:.2f} ({m['ci95'][0]:.2f}--{m['ci95'][1]:.2f})"


def shares(path):
    sources = [c["source"] for e in json.loads(path.read_text())["entries"].values() for c in e["citations"]]
    counts = Counter(next(label for label, prefix in SOURCES if s.startswith(prefix)) for s in sources)
    return {label: 100 * counts[label] / len(sources) for label, _ in SOURCES}


def main():
    res = json.loads(RESULTS.read_text())
    base, imp = res["systems"]["baseline"], res["systems"]["improved"]
    rows = [f"{label} & {cell(base[key])} & {cell(imp[key])} \\\\" for key, label in METRICS]
    share = {name: shares(path) for name, path in CACHES.items()}
    rows.append("\\midrule")
    rows.append("\\multicolumn{3}{@{}l}{\\emph{Share of all retrieved passages (207 patients $\\times$ 5)}} \\\\")
    rows += [f"\\quad {label} & {share['baseline'][label]:.1f}\\% & {share['improved'][label]:.1f}\\% \\\\" for label, _ in SOURCES]
    s = res["signTestP5"]
    p = "$p<0.001$" if s["p"] < 0.001 else f"$p={s['p']:.3f}$"
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        "% Generated by research/retrieval_table.py from research/retrieval_eval/results.json and the retrieval caches. Do not edit by hand.\n"
        "\\begin{table}[t]\n\\centering\n"
        f"\\caption{{Retrieval quality before and after the changes, on {res['cases']} random patients (mean, 95\\% CI). "
        f"Precision at 5 was higher for the final pipeline for {s['improvedBetter']} patients and lower for {s['baselineBetter']} (sign test, {p}).}}\n"
        "\\label{tab:retrieval}\n\\footnotesize\n\\setlength{\\tabcolsep}{4pt}\n\\begin{tabular}{@{}lcc@{}}\n\\toprule\n"
        "Measure & Earlier pipeline & Final pipeline \\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
